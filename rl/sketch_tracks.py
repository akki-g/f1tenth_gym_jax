def smooth_boundary(points, *, closed=True, samples_per_segment=16):
    """Interpolate an ordered polyline with a centripetal Catmull–Rom spline.

    Unlike rounding with a moving average, the curve passes through each
    landmark. Open endpoints stay fixed, so attached walls remain attached.
    Set samples_per_segment=1 to return the original straight segments.
    """
    p = np.asarray(points, dtype=float)
    if p.ndim != 2 or p.shape[1] != 2 or not np.isfinite(p).all():
        raise ValueError("points must be a finite (N, 2) coordinate array")
    if len(p) > 1 and np.array_equal(p[0], p[-1]) and closed:
        p = p[:-1]
    if len(p) < (3 if closed else 2):
        raise ValueError("Use at least 3 closed or 2 open boundary points")
    if not isinstance(samples_per_segment, (int, np.integer)) or samples_per_segment < 1:
        raise ValueError("samples_per_segment must be a positive integer")
    if np.any(np.linalg.norm(np.diff(p, axis=0), axis=1) == 0):
        raise ValueError("Consecutive boundary points must be distinct")
    if samples_per_segment == 1:
        return np.vstack((p, p[0])) if closed else p.copy()

    # Wrap a closed curve; extrapolate one point at each open endpoint.
    extended = (
        np.vstack((p[-1], p, p[0], p[1]))
        if closed else
        np.vstack((2 * p[0] - p[1], p, 2 * p[-1] - p[-2]))
    )
    segments = []
    for i in range(len(p) if closed else len(p) - 1):
        q = extended[i:i + 4]
        # alpha=0.5: centripetal spacing reduces spline overshoot.
        t = np.r_[0.0, np.cumsum(np.sqrt(np.linalg.norm(np.diff(q, axis=0), axis=1)))]
        u = np.linspace(t[1], t[2], samples_per_segment, endpoint=False)[:, None]
        a1 = (t[1] - u) / (t[1] - t[0]) * q[0] + (u - t[0]) / (t[1] - t[0]) * q[1]
        a2 = (t[2] - u) / (t[2] - t[1]) * q[1] + (u - t[1]) / (t[2] - t[1]) * q[2]
        a3 = (t[3] - u) / (t[3] - t[2]) * q[2] + (u - t[2]) / (t[3] - t[2]) * q[3]
        b1 = (t[2] - u) / (t[2] - t[0]) * a1 + (u - t[0]) / (t[2] - t[0]) * a2
        b2 = (t[3] - u) / (t[3] - t[1]) * a2 + (u - t[1]) / (t[3] - t[1]) * a3
        segments.append((t[2] - u) / (t[2] - t[1]) * b1 + (u - t[1]) / (t[2] - t[1]) * b2)
    return np.vstack((*segments, p[0] if closed else p[-1]))
